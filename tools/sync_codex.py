"""Generate Codex agents and workflow from claude/; --check verifies committed output."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generated():
    files = {}
    for path in sorted((ROOT / "claude/agents").glob("*.md")):
        _, frontmatter, body = path.read_text(encoding="utf-8").split("---", 2)
        description = re.search(r"^description: (.+)$", frontmatter, re.M).group(1)
        description = description.replace("SendMessage", "a follow-up task")
        body = body.strip().replace(".claude/skills/", ".agents/skills/")
        # Claude's named file tools and Bash working-directory assumptions don't apply to Codex.
        body = re.sub(
            r"## Where you work\n.*?(?=## Read)",
            "## Where you work\n\n"
            "Use your shell's workdir option to run commands in the job worktree, and absolute paths "
            "for file operations. All code changes and commits belong to the job branch there. "
            "The job folder is in the main checkout; only write your assigned report there. "
            "Never edit other files in the main checkout.\n\n"
            "Use the tools available in this Codex session to read, search, edit and run commands. "
            "Follow the inherited sandbox and approval policy. If required access is unavailable, "
            "report the blocker in your assigned file. Never change permissions yourself.\n\n"
            "Never touch the user's running app, database, containers, services or data. "
            "Start anything you need from the worktree on your assigned ports with throwaway data, "
            "then stop only the processes you started.\n\n",
            body,
            flags=re.S,
        )
        body = body.replace("SendMessage", "a follow-up task")
        metadata = "\n".join(line for line in frontmatter.splitlines()
                             if re.match(r"^(type|output|contract):", line))
        files[Path(f"codex/agents/{path.stem}.md")] = (
            "---\n"
            f"name: {path.stem}\n"
            f"description: {description}\n" + metadata + "\n---\n\n"
            "<!-- Generated by tools/sync_codex.py; edit claude/agents/ instead. -->\n\n" + body +
            "\n")
    text = (ROOT /
            "claude/skills/factory/references/workflow.md").read_text(encoding="utf-8").strip()
    text = re.sub(r"(?<![\w/<>.-])/factory\b", "$factory", text).replace("Claude", "Codex")
    text = text.replace("--provider claude",
                        "--provider codex").replace("provider=claude", "provider=codex")
    text = text.replace(".claude/agents/", ".codex/agents/")
    text = text.replace("this file and the agent files",
                        "the source files under claude/ and regenerate the Codex files")
    text = text.replace("Agent (`subagent_type`)", "Codex agent role")
    text = re.sub(r"\bAgent\s+tool\b", "native subagent tool",
                  text).replace("SendMessage", "a native follow-up task")
    text = text.replace(
        "Spawn all four reviewers **in one message**, so they run in parallel.",
        "Schedule all four reviewers in parallel up to the session's capacity. "
        "As slots become free, start remaining reviewers; do not exceed the available slots.",
    )
    text = text.replace(
        "1. Run `python factory/job.py wait --watcher <id>` from `<repo>`, with the Bash\n"
        "   tool's timeout at its maximum. It returns within 9 minutes.",
        "1. Run `python factory/job.py wait --watcher <id> --timeout 45` from `<repo>`. "
        "Use your shell tool's asynchronous polling if needed, so you can still receive user input.",
    )
    text = text.replace("job.py wait --watcher", "job.py wait --provider codex --watcher")
    text = text.replace("Claim it with one Edit", "Claim it with one conditional file edit")
    text = text.replace("the\nEdit fails", "the\nedit fails")
    files[Path("codex/skills/factory/references/workflow.md")] = (
        "<!-- Generated by tools/sync_codex.py; edit claude/skills/factory/references/workflow.md instead. -->\n\n"
        + text + "\n")
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for relative, content in generated().items():
        path = ROOT / relative
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        if args.check:
            stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as out:
                out.write(content)
            print(relative)
    if stale:
        parser.exit(1, "Regenerate with python tools/sync_codex.py:\n" + "\n".join(stale) + "\n")


if __name__ == "__main__":
    main()
